-- CArchive schema (PostgreSQL / Neon)
-- Run once with the ADMIN connection string (never the app role's).
-- Safe to re-run: everything uses IF NOT EXISTS.

-- ---------------------------------------------------------------- users
CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username      VARCHAR(30)  NOT NULL,
    email         VARCHAR(120) NOT NULL,
    password_hash TEXT         NOT NULL,              -- argon2 hash, never the password
    role          VARCHAR(10)  NOT NULL DEFAULT 'user',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT users_username_format CHECK (username ~ '^[A-Za-z0-9_.-]{3,30}$'),
    CONSTRAINT users_email_has_at    CHECK (position('@' IN email) > 1),
    CONSTRAINT users_role_valid      CHECK (role IN ('user', 'admin'))
);

-- case-insensitive uniqueness: "Maya" and "maya" are the same person
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_key ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_key    ON users (lower(email));

-- ---------------------------------------------------------------- cats
-- IDs are GENERATED BY DEFAULT (not ALWAYS) only so seed.py can keep the
-- original IDs 1-20; the API never supplies an id.
CREATE TABLE IF NOT EXISTS cats (
    id                         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                       VARCHAR(100) NOT NULL,
    image                      TEXT         NOT NULL DEFAULT '',
    breed                      VARCHAR(100) NOT NULL,
    age                        INTEGER      NOT NULL,
    color                      VARCHAR(100) NOT NULL,
    gender                     VARCHAR(10)  NOT NULL,
    country                    VARCHAR(100) NOT NULL,
    prev_owner                 VARCHAR(100) NOT NULL DEFAULT 'Anonymous',  -- display name of the submitter
    fav_treat                  VARCHAR(100) NOT NULL DEFAULT 'Unknown',
    likes                      TEXT         NOT NULL DEFAULT '',
    dislikes                   TEXT         NOT NULL DEFAULT '',
    previous_health_conditions TEXT         NOT NULL DEFAULT 'None',
    friendliness_level         INTEGER      NOT NULL DEFAULT 3,
    prefered_environment       VARCHAR(20)  NOT NULL DEFAULT 'Inside Only',  -- spelling kept: the frontends use it
    good_for_adoption          VARCHAR(3)   NOT NULL DEFAULT 'No',
    description                TEXT         NOT NULL,

    -- moderation and provenance
    status     VARCHAR(10) NOT NULL DEFAULT 'pending',     -- pending | approved | rejected
    source     VARCHAR(10) NOT NULL DEFAULT 'community',   -- original (seed data) | community
    user_id    INTEGER REFERENCES users (id) ON DELETE SET NULL,  -- NULL for the original 20
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT cats_name_not_blank        CHECK (btrim(name) <> ''),
    CONSTRAINT cats_breed_not_blank       CHECK (btrim(breed) <> ''),
    CONSTRAINT cats_color_not_blank       CHECK (btrim(color) <> ''),
    CONSTRAINT cats_country_not_blank     CHECK (btrim(country) <> ''),
    CONSTRAINT cats_description_not_blank CHECK (btrim(description) <> ''),
    CONSTRAINT cats_age_range             CHECK (age BETWEEN 1 AND 40),
    CONSTRAINT cats_gender_valid          CHECK (gender IN ('Male', 'Female')),
    CONSTRAINT cats_friendliness_range    CHECK (friendliness_level BETWEEN 1 AND 5),
    CONSTRAINT cats_environment_valid     CHECK (prefered_environment IN ('Inside Only', 'Outside Only', 'Outside and Inside')),
    CONSTRAINT cats_adoption_valid        CHECK (good_for_adoption IN ('Yes', 'No')),
    CONSTRAINT cats_status_valid          CHECK (status IN ('pending', 'approved', 'rejected')),
    CONSTRAINT cats_source_valid          CHECK (source IN ('original', 'community'))
);

-- duplicate guard: same cat, same breed, same country, same submitter
CREATE UNIQUE INDEX IF NOT EXISTS cats_no_duplicates
    ON cats (lower(name), lower(breed), lower(country), lower(prev_owner));

-- every public query filters on status; "my cats" filters on user_id
CREATE INDEX IF NOT EXISTS cats_status_idx  ON cats (status);
CREATE INDEX IF NOT EXISTS cats_user_id_idx ON cats (user_id);
